using System.Text;

using Microsoft.CodeAnalysis;

namespace Hlibz.UseCases.Generators;

/// <summary>
/// Writes the generated source: the assembly's <c>UseCaseManifestAttribute</c>, the attribute
/// applied to the assembly, and one pipeline class per handler.
/// </summary>
internal static class ManifestWriter
{
    private const string Namespace = "Hlibz.UseCases.Generated";
    private const string Library = "global::Hlibz.UseCases";
    private const string Services = "global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions";
    private const string TryAdd = "global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions";
    private const string Resolve = "global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService";

    private static string GeneratorName => typeof(ManifestWriter).Assembly.GetName().Name;

    private static string GeneratorVersion =>
        typeof(ManifestWriter).Assembly.GetName().Version?.ToString() ?? "0.0.0.0";

    /// <summary>
    /// The manifest class's name for the assembly being compiled, unique to it so assemblies that
    /// see each other's internals don't clash, or <see langword="null"/> when the compilation
    /// doesn't reference the library (nothing to generate).
    /// </summary>
    /// <param name="compilation">The compilation.</param>
    /// <returns>The class name, or <see langword="null"/>.</returns>
    public static string? ClassNameFor(Compilation compilation)
    {
        if (compilation.GetTypeByMetadataName(SymbolNames.Manifest) is null)
        {
            return null;
        }

        StringBuilder name = new("UseCaseManifest_");
        foreach (char character in compilation.AssemblyName ?? "Assembly")
        {
            name.Append(char.IsLetterOrDigit(character) ? character : '_');
        }

        return name.ToString();
    }

    /// <summary>
    /// Writes the manifest and the pipelines.
    /// </summary>
    /// <param name="className">The manifest class's name.</param>
    /// <param name="handlers">The handlers to register, in order.</param>
    /// <param name="types">The validatable types, in order.</param>
    /// <returns>The source.</returns>
    public static string Write(
        string className,
        IReadOnlyList<HandlerModel> handlers,
        IReadOnlyList<TypeModel> types)
    {
        StringBuilder source = new();
        source.Append(
            $$"""
            // <auto-generated/>
            #nullable enable
            // Obsolete handlers and use cases are still registered.
            #pragma warning disable CS0612, CS0618

            [assembly: global::{{Namespace}}.{{className}}]

            namespace {{Namespace}}
            {
                /// <summary>
                /// The use cases and validatable types the Hlibz.UseCases source generator found in
                /// this assembly, read by AddUseCases.
                /// </summary>
                [global::System.CodeDom.Compiler.GeneratedCode("{{GeneratorName}}", "{{GeneratorVersion}}")]
                internal sealed class {{className}} : {{Library}}.UseCaseManifestAttribute
                {
                    private static readonly {{Library}}.UseCaseRegistration[] AllUseCases =
                    {

            """);

        for (int index = 0; index < handlers.Count; index++)
        {
            WriteRegistration(source, handlers[index], index);
        }

        source.Append(
            $$"""
                    };

                    private static readonly {{Library}}.ValidatableType[] AllValidatableTypes =
                    {

            """);

        foreach (TypeModel type in types)
        {
            WriteType(source, type);
        }

        source.Append(
            $$"""
                    };

                    /// <inheritdoc/>
                    public override global::System.Collections.Generic.IReadOnlyList<{{Library}}.UseCaseRegistration> UseCases => AllUseCases;

                    /// <inheritdoc/>
                    public override global::System.Collections.Generic.IReadOnlyList<{{Library}}.ValidatableType> ValidatableTypes => AllValidatableTypes;
                }

            """);

        for (int index = 0; index < handlers.Count; index++)
        {
            WritePipeline(source, handlers[index], index);
        }

        source.Append("}\n");
        return source.ToString();
    }

    private static void WriteRegistration(StringBuilder source, HandlerModel handler, int index)
    {
        string result = handler.ResultName is null ? "null" : $"typeof({handler.ResultName})";
        string generic = handler.HandlerInterface;
        source.Append(
            $$"""
                        new {{Library}}.UseCaseRegistration(
                            typeof({{handler.UseCaseName}}),
                            typeof({{handler.HandlerName}}),
                            {{result}},
                            static services =>
                            {
                                {{TryAdd}}.TryAddScoped<{{handler.HandlerName}}>(services);
                                {{Services}}.AddScoped<{{generic}}>(
                                    services,
                                    static provider => new UseCasePipeline{{index}}(
                                        {{Resolve}}<{{handler.HandlerName}}>(provider),
                                        {{Resolve}}<{{Library}}.UseCasePipeline>(provider)));

            """);

        foreach (string own in handler.Interfaces)
        {
            source.Append(
                $$"""
                                {{Services}}.AddScoped<{{own}}>(
                                    services,
                                    static provider => ({{own}}){{Resolve}}<{{generic}}>(provider));

                """);
        }

        source.Append(
            $$"""
                                {{Services}}.AddScoped<{{Library}}.IUseCaseHandler>(
                                    services,
                                    static provider => {{Resolve}}<{{generic}}>(provider));
                            }),

            """);
    }

    private static void WriteType(StringBuilder source, TypeModel type)
    {
        source.Append(
            $$"""
                        new {{Library}}.ValidatableType(
                            typeof({{type.Name}}),
                            new {{Library}}.ValidatableProperty[]
                            {

            """);

        foreach (PropertyModel property in type.Properties)
        {
            string collection = property.IsCollection ? "true" : "false";
            source.Append(
                $$"""
                                new {{Library}}.ValidatableProperty(
                                    typeof({{property.DeclaringTypeName}}),
                                    "{{property.MetadataName}}",
                                    static instance => (({{type.Name}})instance).{{property.Name}},
                                    {{collection}}),

                """);
        }

        source.Append(
            """
                            }),

            """);
    }

    private static void WritePipeline(StringBuilder source, HandlerModel handler, int index)
    {
        string interfaces = string.Join(", ", new[] { handler.HandlerInterface }.Concat(handler.Interfaces));
        string returns = handler.ResultArgument is null
            ? "global::System.Threading.Tasks.Task<global::Hlibz.Results.Result>"
            : $"global::System.Threading.Tasks.Task<global::Hlibz.Results.Result<{handler.ResultArgument}>>";
        string invoke = handler.ResultArgument is null
            ? $"InvokeAsync<{handler.UseCaseArgument}>"
            : $"InvokeAsync<{handler.UseCaseArgument}, {handler.ResultArgument}>";
        source.Append(
            $$"""

                /// <summary>
                /// {{handler.HandlerName.Replace("global::", string.Empty)}} wrapped in its pipeline: validation, the
                /// filters, then the handler.
                /// </summary>
                [global::System.CodeDom.Compiler.GeneratedCode("{{GeneratorName}}", "{{GeneratorVersion}}")]
                file sealed class UseCasePipeline{{index}} : {{interfaces}}
                {
                    private readonly {{handler.HandlerName}} _handler;
                    private readonly {{Library}}.UseCasePipeline _pipeline;

                    public UseCasePipeline{{index}}({{handler.HandlerName}} handler, {{Library}}.UseCasePipeline pipeline)
                    {
                        _handler = handler;
                        _pipeline = pipeline;
                    }

                    public {{returns}} HandleAsync({{handler.UseCaseArgument}} useCase, global::System.Threading.CancellationToken cancellationToken = default) =>
                        _pipeline.{{invoke}}(useCase, _handler, cancellationToken);
                }

            """);
    }
}
